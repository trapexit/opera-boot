#!/usr/bin/env python3
# opera-boot (GPL-2.0-only): generate the packed startup caption offline.
import argparse
from datetime import date
from pathlib import Path


# Original 5x7 glyphs: each row occupies the low five bits, leftmost bit first.
# Preserve the existing caption's shapes; complete its digits for arbitrary dates.
GLYPHS = {
    "O": (0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E),
    "p": (0x00, 0x00, 0x1E, 0x11, 0x1E, 0x10, 0x10),
    "e": (0x00, 0x00, 0x0E, 0x11, 0x1F, 0x10, 0x0E),
    "r": (0x00, 0x00, 0x16, 0x19, 0x10, 0x10, 0x10),
    "a": (0x00, 0x00, 0x0E, 0x01, 0x0F, 0x11, 0x0F),
    " ": (0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
    "B": (0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E),
    "o": (0x00, 0x00, 0x0E, 0x11, 0x11, 0x11, 0x0E),
    "t": (0x08, 0x08, 0x1C, 0x08, 0x08, 0x09, 0x06),
    "(": (0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02),
    ")": (0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08),
    "-": (0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00),
    "0": (0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E),
    "1": (0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E),
    "2": (0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F),
    "3": (0x1F, 0x01, 0x01, 0x0E, 0x01, 0x01, 0x1F),
    "4": (0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02),
    "5": (0x1F, 0x10, 0x10, 0x1E, 0x01, 0x01, 0x1E),
    "6": (0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E),
    "7": (0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08),
    "8": (0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E),
    "9": (0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C),
}
GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7


def parse_date(value):
    try:
        parsed = date.fromisoformat(value)
    except ValueError:
        raise argparse.ArgumentTypeError("expected a valid YYYY-MM-DD date") from None
    if parsed.isoformat() != value:
        raise argparse.ArgumentTypeError("expected a valid YYYY-MM-DD date")
    return parsed


def caption_header(build_date):
    caption = f"Opera Boot ({build_date.isoformat()})"
    rows = [
        "0".join(f"{GLYPHS[char][y]:0{GLYPH_WIDTH}b}" for char in caption)
        for y in range(GLYPH_HEIGHT)
    ]
    # Retain six-column advances, trimming only unused columns after the last ink.
    width = max(len(row.rstrip("0")) for row in rows)
    row_bytes = (width + 7) // 8
    initializers = []
    for row in rows:
        packed = int(row[:width].ljust(row_bytes * 8, "0"), 2).to_bytes(row_bytes, "big")
        values = ", ".join(f"0x{value:02X}" for value in packed)
        initializers.append(f"    {{ {values} }}")
    return (
        "#pragma once\n\n"
        "// Generated by tools/gen_caption.py; do not edit.\n"
        f'// Original 5x7 glyphs, packed MSB-first: "{caption}".\n'
        f"#define CAPTION_WIDTH  {width}\n"
        f"#define CAPTION_HEIGHT {GLYPH_HEIGHT}\n"
        "#define CAPTION_BYTES  ((CAPTION_WIDTH + 7) / 8)\n\n"
        "static const u8 caption_rows[CAPTION_HEIGHT][CAPTION_BYTES] =\n"
        "  {\n" + ",\n".join(initializers) + "\n  };\n"
    )


def main():
    parser = argparse.ArgumentParser(description="Generate the startup build-date caption header.")
    parser.add_argument("build_date", type=parse_date, metavar="YYYY-MM-DD")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    content = caption_header(args.build_date).encode("ascii")
    try:
        if args.output.exists() and args.output.read_bytes() == content:
            return
        args.output.write_bytes(content)
    except OSError as error:
        parser.exit(1, f"gen_caption: {error}\n")


if __name__ == "__main__":
    main()
